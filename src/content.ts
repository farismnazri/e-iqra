export type UnitId = keyof typeof units
export type Exercise = {
  id: string
  units: UnitId[]
  curriculumVersion: typeof curriculumVersion | typeof chapter2CurriculumVersion
  teacherStatus: 'unreviewed'
  kind: 'isolated_unit' | 'separated_units'
}

type DraftPageSpec = {
  number: number
  sourcePage: number
  blockId: string
  phase: 'introduce' | 'mix' | 'review'
  title: string
  goal: string
  // Source page and suffix are historical identity, independent of pagination.
  // Retained eNN and v3-eNN IDs keep exactly their original unit sequences.
  items: [suffix: string, separatedUnits: string][]
}
function draftPage({ number, sourcePage, blockId, phase, title, goal, items }: DraftPageSpec) {
  const sourceId = `${chapterId}-p${String(sourcePage).padStart(2, '0')}`
  const exercises: Exercise[] = items.map(([suffix, sequence]) => {
    const forms = sequence.split(' ').map(name => {
      const unitId = `draft-${name}`
      if (!Object.hasOwn(units, unitId)) throw new Error(`Unknown draft form: ${name}`)
      return unitId as UnitId
    })
    return {
      id: `${sourceId}-${suffix}`, units: forms, curriculumVersion, teacherStatus: 'unreviewed',
      kind: forms.length === 1 ? 'isolated_unit' : 'separated_units',
    }
  })
  return {
    id: `${chapterId}-p${String(number).padStart(2, '0')}`,
    blockId, phase, title, goal, curriculumVersion, teacherStatus: 'unreviewed' as const,
    // Write uses only the exact forms read on this displayed page.
    eligibleForms: [...new Set(exercises.flatMap(exercise => exercise.units))], exercises,
  }
}

