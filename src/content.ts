export type UnitId = keyof typeof units
export type Exercise = {
  id: string
  units: UnitId[]
  curriculumVersion: typeof curriculumVersion
  teacherStatus: 'unreviewed'
  kind: 'isolated_unit' | 'separated_units'
}

type DraftPageSpec = {
  number: number
  blockId: string
  phase: 'introduce' | 'mix' | 'review'
  title: string
  goal: string
  // Explicit suffixes stay with their content when exercises move within a page.
  // Existing eNN IDs retain exactly their old unit sequence. v3-eNN IDs are new.
  items: [suffix: string, separatedUnits: string][]
}
function draftPage({ number, blockId, phase, title, goal, items }: DraftPageSpec) {
  const id = `${chapterId}-p${String(number).padStart(2, '0')}`
  const exercises: Exercise[] = items.map(([suffix, sequence]) => {
    const forms = sequence.split(' ').map(name => {
      const unitId = `draft-${name}`
      if (!Object.hasOwn(units, unitId)) throw new Error(`Unknown draft form: ${name}`)
      return unitId as UnitId
    })
    return {
      id: `${id}-${suffix}`, units: forms, curriculumVersion, teacherStatus: 'unreviewed',
      kind: forms.length === 1 ? 'isolated_unit' : 'separated_units',
    }
  })
  return {
    id, blockId, phase, title, goal, curriculumVersion, teacherStatus: 'unreviewed' as const,
    // Write uses only the exact letter/vowel forms actually read on this page.
    eligibleForms: [...new Set(exercises.flatMap(item => item.units))], exercises,
  }
}

